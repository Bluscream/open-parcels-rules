/*
 * Files generated from the code: the JSON Schemas (from the zod schemas, which are the source
 * of truth) and the portability report of the vendored upstream patterns.
 */
import { readFileSync } from "node:fs";
import { basename, join } from "node:path";
import { z } from "zod";
import { portabilityProblems } from "../src/portability.ts";
import { bundleSchema } from "../src/schema/bundle.ts";
import { carriersFileSchema } from "../src/schema/carriers.ts";
import { keysFileSchema } from "../src/schema/keys.ts";
import { localeFileSchema } from "../src/schema/locale.ts";
import { mailRuleSchema } from "../src/schema/mail.ts";
import { statusFileSchema } from "../src/schema/status.ts";
import { courierFileSchema } from "../src/schema/tracking.ts";
import { listFiles, ROOT, VENDOR_COURIERS } from "./collect.ts";

const SCHEMAS: Readonly<Record<string, z.ZodType>> = {
  "carriers.schema.json": carriersFileSchema,
  "tracking-numbers.schema.json": courierFileSchema,
  "status.schema.json": statusFileSchema,
  "keys.schema.json": keysFileSchema,
  "locale.schema.json": localeFileSchema,
  "mail-rule.schema.json": mailRuleSchema,
  "bundle.schema.json": bundleSchema,
};

function jsonSchema(name: string, schema: z.ZodType): string {
  const generated = z.toJSONSchema(schema, { io: "input", target: "draft-2020-12" });
  const withId = {
    $id: `https://raw.githubusercontent.com/Bluscream/open-parcels-rules/main/schema/${name}`,
    ...generated,
  };
  return `${JSON.stringify(withId, null, 2)}\n`;
}

function portabilityReport(): string {
  const rows: string[] = [];
  for (const path of listFiles(VENDOR_COURIERS, ".json")) {
    const courier = JSON.parse(readFileSync(path, "utf8")) as {
      tracking_numbers: { id?: string; name: string; regex: string | string[] }[];
    };
    for (const type of courier.tracking_numbers) {
      const pattern = Array.isArray(type.regex) ? type.regex.join("") : type.regex;
      const problems = portabilityProblems(pattern);
      if (problems.length > 0) {
        rows.push(`| ${basename(path)} | ${type.id ?? type.name} | ${problems.join(", ")} |`);
      }
    }
  }
  return [
    "# Portability of the vendored patterns",
    "",
    "Generated by `npm run generate`; do not edit. The vendored files stay byte-identical to",
    "upstream, so these patterns are used as they are. The TypeScript engine runs all of them;",
    "ports to engines without the listed features (Go RE2 in particular) have to skip or",
    "rewrite these entries.",
    "",
    "| File | Format | Outside the portable subset |",
    "| --- | --- | --- |",
    ...(rows.length === 0 ? ["| (none) | | |"] : rows),
    "",
  ].join("\n");
}

/** Relative path to expected content of every generated file. */
export function generatedFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const [name, schema] of Object.entries(SCHEMAS)) {
    files.set(`schema/${name}`, jsonSchema(name, schema));
  }
  files.set("vendor/tracking_number_data/PORTABILITY.md", portabilityReport());
  return files;
}

export function absolute(relative: string): string {
  return join(ROOT, relative);
}
